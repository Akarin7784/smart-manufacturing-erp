CREATE TABLE IF NOT EXISTS fin_arap_bill (
  id BIGINT AUTO_INCREMENT PRIMARY KEY,
  bill_no VARCHAR(64) NOT NULL UNIQUE,
  bill_type VARCHAR(8) NOT NULL,
  partner_id BIGINT NOT NULL,
  source_biz_type VARCHAR(32),
  source_biz_no VARCHAR(64),
  amount DECIMAL(18,2) NOT NULL,
  settled_amount DECIMAL(18,2) DEFAULT 0,
  status VARCHAR(16) NOT NULL,
  due_date DATE,
  version INT NOT NULL DEFAULT 0,
  created_at DATETIME DEFAULT CURRENT_TIMESTAMP,
  updated_at DATETIME DEFAULT CURRENT_TIMESTAMP,
  created_by VARCHAR(64),
  deleted TINYINT DEFAULT 0,
  UNIQUE (source_biz_type, source_biz_no),
  INDEX idx_arap_partner (partner_id, bill_type)
);

CREATE TABLE IF NOT EXISTS fin_payment (
  id BIGINT AUTO_INCREMENT PRIMARY KEY,
  payment_no VARCHAR(64) NOT NULL UNIQUE,
  payment_type VARCHAR(16) NOT NULL,
  partner_id BIGINT NOT NULL,
  amount DECIMAL(18,2) NOT NULL,
  applied_amount DECIMAL(18,2) NOT NULL DEFAULT 0,
  paid_date DATE,
  remark VARCHAR(255),
  version INT NOT NULL DEFAULT 0,
  created_at DATETIME DEFAULT CURRENT_TIMESTAMP,
  updated_at DATETIME DEFAULT CURRENT_TIMESTAMP,
  created_by VARCHAR(64),
  deleted TINYINT DEFAULT 0,
  INDEX idx_payment_partner (partner_id)
);
CREATE TABLE IF NOT EXISTS fin_settlement (
  id BIGINT AUTO_INCREMENT PRIMARY KEY,
  request_no VARCHAR(64) NOT NULL UNIQUE,
  payment_id BIGINT NOT NULL,
  bill_id BIGINT NOT NULL,
  amount DECIMAL(18,2) NOT NULL,
  created_at DATETIME DEFAULT CURRENT_TIMESTAMP,
  updated_at DATETIME DEFAULT CURRENT_TIMESTAMP,
  created_by VARCHAR(64),
  deleted TINYINT DEFAULT 0,
  INDEX idx_settlement_bill (bill_id)
);
-- 单据号序列（#18 a）：seq_key = 前缀 + yyyyMMdd，val 原子递增；多实例共用，保证单据号全局唯一
CREATE TABLE IF NOT EXISTS sys_doc_seq (
  seq_key VARCHAR(64) NOT NULL PRIMARY KEY,
  val BIGINT NOT NULL
);
CREATE TABLE IF NOT EXISTS sys_idempotency (
  id BIGINT AUTO_INCREMENT PRIMARY KEY, user_name VARCHAR(64) NOT NULL, idem_key VARCHAR(128) NOT NULL,
  req_hash CHAR(64) NOT NULL, status VARCHAR(16) NOT NULL, result_id BIGINT,
  created_at DATETIME NOT NULL, expires_at DATETIME NOT NULL,
  UNIQUE KEY uk_idem_user_key (user_name, idem_key), INDEX idx_idem_expires (expires_at));

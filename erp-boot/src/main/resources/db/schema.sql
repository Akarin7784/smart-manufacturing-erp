CREATE TABLE IF NOT EXISTS wf_approval_instance (
  id BIGINT AUTO_INCREMENT PRIMARY KEY,
  biz_type VARCHAR(32) NOT NULL,
  biz_id BIGINT NOT NULL,
  biz_no VARCHAR(64),
  status VARCHAR(16) NOT NULL,
  applicant VARCHAR(64),
  approver VARCHAR(64),
  comment VARCHAR(255),
  amount DECIMAL(18,2),
  node_plan VARCHAR(512),
  approver_snapshot VARCHAR(4000),
  current_index INT NOT NULL DEFAULT 0,
  version INT NOT NULL DEFAULT 0,
  finished_at DATETIME,
  created_at DATETIME DEFAULT CURRENT_TIMESTAMP,
  updated_at DATETIME DEFAULT CURRENT_TIMESTAMP,
  created_by VARCHAR(64),
  deleted TINYINT DEFAULT 0
);
CREATE TABLE IF NOT EXISTS wf_process_def (
  id BIGINT AUTO_INCREMENT PRIMARY KEY,
  biz_type VARCHAR(32) NOT NULL UNIQUE,
  name VARCHAR(64) NOT NULL,
  enabled TINYINT NOT NULL DEFAULT 1,
  created_at DATETIME DEFAULT CURRENT_TIMESTAMP,
  updated_at DATETIME DEFAULT CURRENT_TIMESTAMP,
  created_by VARCHAR(64),
  version INT NOT NULL DEFAULT 0,
  deleted TINYINT DEFAULT 0
);
CREATE TABLE IF NOT EXISTS wf_node_def (
  id BIGINT AUTO_INCREMENT PRIMARY KEY,
  process_id BIGINT NOT NULL,
  seq INT NOT NULL,
  name VARCHAR(64) NOT NULL,
  role_code VARCHAR(64) NOT NULL,
  approve_mode VARCHAR(8) NOT NULL,
  min_amount DECIMAL(18,2),
  created_at DATETIME DEFAULT CURRENT_TIMESTAMP,
  updated_at DATETIME DEFAULT CURRENT_TIMESTAMP,
  created_by VARCHAR(64),
  deleted TINYINT DEFAULT 0,
  INDEX idx_node_process (process_id, seq)
);
CREATE TABLE IF NOT EXISTS wf_approval_record (
  id BIGINT AUTO_INCREMENT PRIMARY KEY,
  instance_id BIGINT NOT NULL,
  node_id BIGINT,
  node_name VARCHAR(64),
  node_index INT NOT NULL DEFAULT 0,
  approver VARCHAR(64) NOT NULL,
  action VARCHAR(16) NOT NULL,
  comment VARCHAR(255),
  created_at DATETIME DEFAULT CURRENT_TIMESTAMP,
  updated_at DATETIME DEFAULT CURRENT_TIMESTAMP,
  created_by VARCHAR(64),
  deleted TINYINT DEFAULT 0,
  UNIQUE KEY uk_record_approver (instance_id, node_index, approver)
);

CREATE TABLE IF NOT EXISTS inv_stock (
  id BIGINT AUTO_INCREMENT PRIMARY KEY,
  material_id BIGINT NOT NULL,
  warehouse_id BIGINT NOT NULL,
  qty DECIMAL(18,4) NOT NULL DEFAULT 0,
  version INT NOT NULL DEFAULT 0,
  created_at DATETIME DEFAULT CURRENT_TIMESTAMP,
  updated_at DATETIME DEFAULT CURRENT_TIMESTAMP,
  created_by VARCHAR(64),
  deleted TINYINT DEFAULT 0,
  UNIQUE (material_id, warehouse_id)
);
CREATE TABLE IF NOT EXISTS inv_stock_txn (
  id BIGINT AUTO_INCREMENT PRIMARY KEY,
  txn_no VARCHAR(64) NOT NULL,
  direction VARCHAR(8) NOT NULL,
  material_id BIGINT NOT NULL,
  warehouse_id BIGINT NOT NULL,
  qty DECIMAL(18,4) NOT NULL,
  balance_after DECIMAL(18,4) NOT NULL,
  biz_type VARCHAR(32),
  biz_no VARCHAR(64),
  remark VARCHAR(255),
  created_at DATETIME DEFAULT CURRENT_TIMESTAMP,
  updated_at DATETIME DEFAULT CURRENT_TIMESTAMP,
  created_by VARCHAR(64),
  deleted TINYINT DEFAULT 0
);

